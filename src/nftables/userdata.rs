//! nft's `NFTA_SET_USERDATA` encoding, used to record a set's `typeof` key/value
//! annotations so `nft list` can print them.
//!
//! The wire format (`libnftnl/src/udata.c`) is a flat stream of
//! `[type: u8][len: u8][value]` TLVs; a nested value is simply more TLVs. `nft`
//! builds the tree in `nftables/src/mnl.c::set_key_expression` and the `numgen`
//! leaf in `nftables/src/numgen.c`.
//!
//! We need it because nft has no *named* plain-integer datatype — `integer` is
//! unnameable, `mark` prints hex, and `gid`/`uid`/`realm`/… reject a `numgen`
//! key — so a `typeof numgen random mod 1` annotation is the only way to render
//! a base-10 integer key.
//!
//! The enums below mirror the C ones verbatim (hence the unused variants).
#![allow(dead_code)]

/// `enum nftnl_udata_set_types` (`libnftnl/include/libnftnl/udata.h`).
#[repr(u8)]
enum SetUdata {
    KeyByteOrder = 0,
    DataByteOrder = 1,
    MergeElements = 2,
    KeyTypeof = 3,
    DataTypeof = 4,
    Expr = 5,
    DataInterval = 6,
    Comment = 7,
}

/// `enum { NFTNL_UDATA_SET_TYPEOF_EXPR, NFTNL_UDATA_SET_TYPEOF_DATA }`
/// (`libnftnl/include/libnftnl/udata.h`).
#[repr(u8)]
enum TypeofUdata {
    Expr = 0,
    Data = 1,
}

/// `NFTNL_UDATA_NUMGEN_*` (`nftables/src/numgen.c`).
#[repr(u8)]
enum NumgenUdata {
    Type = 0,
    Mod = 1,
    Offset = 2,
}

/// `enum expr_types` (`nftables/include/expression.h`).
#[repr(u32)]
enum ExprType {
    Verdict = 1,
    Numgen = 23,
}

/// `enum nft_ng_types` (`uapi/linux/netfilter/nf_tables.h`).
#[repr(u32)]
enum NgType {
    Incremental = 0,
    Random = 1,
}

/// `enum byteorder` (`nftables/include/datatype.h`).
#[repr(u32)]
enum ByteOrder {
    Invalid = 0,
    HostEndian = 1,
    BigEndian = 2,
}

/// A TLV type, as it appears on the wire.
trait TlvKind {
    fn kind(self) -> u8;
}

macro_rules! tlv_kind {
    ($($t:ty),*) => {
        $(impl TlvKind for $t {
            fn kind(self) -> u8 {
                self as u8
            }
        })*
    };
}
tlv_kind!(SetUdata, TypeofUdata, NumgenUdata);

/// A `[type: u8][len: u8][value]` TLV.
fn tlv(kind: impl TlvKind, value: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(value.len() + 2);
    out.push(kind.kind());
    out.push(value.len() as u8);
    out.extend_from_slice(value);
    out
}

/// A TLV carrying a host-endian `u32` (`nftnl_udata_put_u32`).
fn u32_tlv(kind: impl TlvKind, value: u32) -> Vec<u8> {
    tlv(kind, &value.to_ne_bytes())
}

/// The userdata of a `typeof numgen random mod <modulus> : verdict` map: a
/// `numgen`-typed key and a `verdict`-typed value.
pub fn numgen_verdict_map(modulus: u32) -> Vec<u8> {
    let mut numgen = Vec::new();
    numgen.extend(u32_tlv(NumgenUdata::Type, NgType::Random as u32));
    numgen.extend(u32_tlv(NumgenUdata::Mod, modulus));
    numgen.extend(u32_tlv(NumgenUdata::Offset, 0));

    let mut key = Vec::new();
    key.extend(u32_tlv(TypeofUdata::Expr, ExprType::Numgen as u32));
    key.extend(tlv(TypeofUdata::Data, &numgen));

    let mut value = Vec::new();
    value.extend(u32_tlv(TypeofUdata::Expr, ExprType::Verdict as u32));
    value.extend(tlv(TypeofUdata::Data, &[]));

    let mut out = Vec::new();
    out.extend(u32_tlv(
        SetUdata::KeyByteOrder,
        ByteOrder::HostEndian as u32,
    ));
    out.extend(u32_tlv(SetUdata::DataByteOrder, ByteOrder::Invalid as u32));
    out.extend(tlv(SetUdata::KeyTypeof, &key));
    out.extend(tlv(SetUdata::DataTypeof, &value));
    out.extend(u32_tlv(SetUdata::DataInterval, 0));
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The generated bytes match what nft writes (captured from a kernel dump),
    /// so `nft list` renders the decimal integer key.
    #[test]
    fn numgen_verdict_map_matches_nft() {
        const EXPECTED: &[u8] = &[
            0, 4, 1, 0, 0, 0, 1, 4, 0, 0, 0, 0, 3, 26, 0, 4, 23, 0, 0, 0, 1, 18, 0, 4, 1, 0, 0, 0,
            1, 4, 1, 0, 0, 0, 2, 4, 0, 0, 0, 0, 4, 8, 0, 4, 1, 0, 0, 0, 1, 0, 6, 4, 0, 0, 0, 0,
        ];
        assert_eq!(numgen_verdict_map(1), EXPECTED);
    }
}
